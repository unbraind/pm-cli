#!/usr/bin/env node
/**
 * Generate the public error-code catalog from literal structured guidance
 * declarations so the vocabulary cannot drift from executable code.
 */
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";

const repositoryRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);

/** Generate or verify the exhaustive error vocabulary for one repository root. */
export async function main(
  root = repositoryRoot,
  args = process.argv.slice(2),
) {
  const sourceRoot = path.join(root, "src");
  const outputPath = path.join(sourceRoot, "sdk", "generated-error-code-catalog.ts");
  const sourceFiles = [];
  const pendingDirectories = [sourceRoot];
  while (pendingDirectories.length > 0) {
    const directory = pendingDirectories.pop();
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      const absolute = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        pendingDirectories.push(absolute);
      } else if (
        entry.isFile() &&
        entry.name.endsWith(".ts") &&
        absolute !== outputPath
      ) {
        sourceFiles.push(absolute);
      }
    }
  }

  const sourcesByCode = new Map();
  for (const absolute of sourceFiles.sort()) {
    const content = await readFile(absolute, "utf8");
    for (const match of content.matchAll(/\bcode:\s*["']([a-z][a-z0-9_]*)["']/g)) {
      const sources = sourcesByCode.get(match[1]) ?? new Set();
      sources.add(path.relative(sourceRoot, absolute).replaceAll(path.sep, "/"));
      sourcesByCode.set(match[1], sources);
    }
  }

  const rows = [...sourcesByCode.entries()]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([code, sources]) => {
      const exitCode =
        code.includes("not_found") || code.startsWith("missing_item")
          ? 3
          : code.includes("conflict") || code.includes("already_")
            ? 4
            : code.includes("dependency_failed")
              ? 5
              : code.includes("invalid") ||
                  code.includes("unknown") ||
                  code.includes("required") ||
                  code.includes("usage")
                ? 2
                : 1;
      const meaning = `${code.replaceAll("_", " ")} condition.`;
      return [
        "  {",
        `    code: ${JSON.stringify(code)},`,
        `    meaning: ${JSON.stringify(meaning[0].toUpperCase() + meaning.slice(1))},`,
        '    stability: "stable",',
        `    exit_code: ${exitCode},`,
        '    recovery: "Inspect the structured error guidance and retry the suggested command.",',
        `    sources: ${JSON.stringify([...sources])},`,
        "  },",
      ].join("\n");
    });

  const generated = `/**
 * @module sdk/generated-error-code-catalog
 *
 * Generated by scripts/generate-error-code-catalog.mjs. Do not edit manually.
 */
import { definePmErrorCodeCatalog } from "./error-code-catalog.js";

/** Exhaustive catalog generated from literal error guidance declarations. */
export const PM_ERROR_CODE_CATALOG = definePmErrorCodeCatalog([
${rows.join("\n")}
]);
`;

  if (args.includes("--check")) {
    const existing = await readFile(outputPath, "utf8").catch(() => "");
    if (existing !== generated) {
      throw new Error(
        "Generated error-code catalog is stale. Run pnpm contracts:errors:update.",
      );
    }
    return;
  }
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, generated, "utf8");
}

/* c8 ignore start -- CLI auto-run guard; logic is covered through main(). */
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  });
}
/* c8 ignore stop */
